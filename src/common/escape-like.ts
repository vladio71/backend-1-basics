// Екранування тексту для LIKE / ILIKE. У шаблоні % означає "будь-що", _ означає "один символ",
// а \ екранує наступний символ. Якщо клієнт шукає саме "100%", ці символи треба позначити
// зворотним слешем, тоді вони шукаються як звичайні. Використовує books.repository.ts.
export function escapeLike(text: string): string {
  return text.replace(/[\\%_]/g, (char) => `\\${char}`);
}
