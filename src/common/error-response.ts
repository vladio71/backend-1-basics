// Єдиний формат відповіді з помилкою для всього API.
// Клієнт завжди отримує ці 4 поля, незалежно від того, де сталася помилка.
// Створює його фільтр помилок (http-exception.filter.ts).
import { ApiProperty } from '@nestjs/swagger';

export class ErrorResponse {
  // HTTP-код. Коли який:
  //   400: клієнт надіслав неправильні дані (валідація DTO не пройшла)
  //   404: запис з таким id не існує
  //   409: запис існує, але дія суперечить стану (немає вільних примірників,
  //        книгу вже повернули, в автора ще є книги)
  //   500: наша помилка, деталі в логах сервера, клієнту їх не показуємо
  @ApiProperty({ example: 404 })
  statusCode: number;

  // Коротка назва помилки англійською, як у стандарті HTTP.
  @ApiProperty({ example: 'Not Found' })
  error: string;

  // Пояснення людською мовою. Для 400 це список полів з проблемами.
  @ApiProperty({ example: 'Книгу з id=42 не знайдено' })
  message: string | string[];

  // Ідентифікатор запиту. Той самий, що в заголовку x-request-id.
  // Потрібен, щоб знайти цей запит у логах сервера.
  @ApiProperty({ example: '0f4b1c2e-3d5a-4f6b-8c7d-9e0f1a2b3c4d' })
  requestId: string;
}
